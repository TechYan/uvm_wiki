def build_source_snippets(root: Path, items: list[dict[str, Any]], radius: int = 18, max_snippets: int = 1800) -> dict[str, Any]:
    wanted: dict[tuple[str, int], None] = {}
    for item in items:
        file = item.get("file")
        line = item.get("line")
        if not file or not line:
            continue
        try:
            line_no = int(line)
        except (TypeError, ValueError):
            continue
        wanted.setdefault((str(file), line_no), None)
        if len(wanted) >= max_snippets:
            break

    cache: dict[str, list[str]] = {}
    snippets: dict[str, Any] = {}
    for (file, line_no) in wanted:
        path = root / file
        try:
            if file not in cache:
                cache[file] = read_text(path).splitlines()
            lines = cache[file]
        except OSError:
            continue
        start = max(1, line_no - radius)
        end = min(len(lines), line_no + radius)
        body = [{"line": idx, "text": lines[idx - 1]} for idx in range(start, end + 1)]
        snippets[f"{file}:{line_no}"] = {"file": file, "line": line_no, "start": start, "end": end, "lines": body}
    return snippets


def build_graph(src: Path, max_nodes: int) -> dict[str, Any]:
    root = src.parent
    files = [p for p in src.rglob("*") if p.is_file() and should_scan(p, root)]
    symbols: list[dict[str, Any]] = []
    edges: list[dict[str, Any]] = []
    for path in sorted(files):
        s, e = scan_file(path, root)
        symbols.extend(s)
        edges.extend(e)

    class_by_name: dict[str, dict[str, Any]] = {}
    for s in symbols:
        if s.get("kind") == "class":
            class_by_name.setdefault(str(s["name"]), s)

    class_names = set(class_by_name)
    # Add class member edges in a second pass, now that class names are known.
    for path in sorted(files):
        rel = path.relative_to(root).as_posix()
        text = strip_comments(read_text(path))
        lines = text.splitlines()
        ranges: list[tuple[str, int, int | None]] = []
        stack: list[tuple[str, int]] = []
        class_line = {int(s["line"]): str(s["name"]) for s in symbols if s.get("kind") == "class" and s.get("file") == rel}
        for lineno, line in enumerate(lines, 1):
            if lineno in class_line:
                stack.append((class_line[lineno], lineno))
            if re.match(r"^\s*endclass\b", line) and stack:
                cls, start = stack.pop()
                ranges.append((cls, start, lineno))
        for cls, start in stack:
            ranges.append((cls, start, None))
        for lineno, line in enumerate(lines, 1):
            owner = class_for_line(ranges, lineno)
            if not owner:
                continue
            m = FIELD_RE.match(line)
            if not m or m.group("type") not in class_names:
                continue
            for var in m.group("vars").split(","):
                inst = var.strip().split("[", 1)[0].strip()
                edges.append({"kind": "has_member", "src": owner, "dst": m.group("type"), "instance": inst, "file": rel, "line": lineno})

    useful = {"extends", "creates", "has_member", "tlm_connect", "seq_item_connect"}
    degree = Counter()
    for e in edges:
        if e.get("kind") not in useful:
            continue
        src_name = str(e.get("src", "")).split(".")[0]
        dst_name = str(e.get("dst", ""))
        if src_name in class_by_name and dst_name in class_by_name:
            degree[src_name] += 1
            degree[dst_name] += 1

    role_priority = {"env": 0, "device": 1, "agent": 2, "driver": 3, "monitor": 4, "sequencer": 5, "scoreboard": 6, "sequence": 7, "sequence_item": 8, "config": 9, "callback": 10, "test": 11, "class": 12}
    selected = sorted(class_by_name.values(), key=lambda n: (role_priority.get(str(n.get("role")), 99), -degree[str(n["name"])], str(n["name"])))[:max_nodes]
    selected_names = {str(n["name"]) for n in selected}
    nodes = [
        {
            "id": str(n["name"]),
            "label": str(n["name"]),
            "role": str(n.get("role", "class")),
            "base": n.get("base"),
            "file": n.get("file"),
            "line": n.get("line"),
            "degree": degree[str(n["name"])],
            "color": ROLE_COLORS.get(str(n.get("role", "class")), ROLE_COLORS["class"]),
        }
        for n in selected
    ]
    graph_edges = []
    facts = []
    for e in edges:
        src_name = str(e.get("src", "")).split(".")[0]
        dst_name = str(e.get("dst", ""))
        if e.get("kind") in useful and src_name in selected_names and dst_name in selected_names:
            graph_edges.append({"source": src_name, "target": dst_name, "kind": e.get("kind"), "label": e.get("instance") or e.get("kind"), "file": e.get("file"), "line": e.get("line")})
        if src_name in selected_names or dst_name in selected_names:
            facts.append(e)
    facts = facts[:4000]
    ports = build_ports(symbols, edges)
    snippets = build_source_snippets(
        root,
        nodes
        + graph_edges
        + facts
        + ports.get("declared", [])
        + ports.get("connections", []),
    )

    return {
        "metadata": {
            "source": str(src),
            "source_root": str(root),
            "source_files": len(files),
            "classes": len(class_by_name),
            "symbols": len(symbols),
            "edges": len(edges),
            "format": "vip_wiki_standalone.v4",
            "notes": [
                "AI-facing atlas generated from readable .sv/.svh/.v files.",
                "Use edges as a navigation cache; verify exact behavior in source before editing.",
            ],
        },
        "symbols": symbols,
        "all_edges": edges,
        "trees": build_trees(symbols, edges),
        "ports": ports,
        "nodes": nodes,
        "edges": graph_edges,
        "facts": facts,
        "snippets": snippets,
        "stats": {"sourceFiles": len(files), "classes": len(class_by_name), "symbols": len(symbols), "edges": len(edges), "visibleNodes": len(nodes), "visibleEdges": len(graph_edges)},
        "roles": sorted({n["role"] for n in nodes}),
        "roleColors": ROLE_COLORS,
    }


