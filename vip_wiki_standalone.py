SOURCE_EXTS = {".sv", ".svh", ".v"}
SKIP_PARTS = {"doc/html", "__MACOSX", ".git"}
SKIP_EXTS = {".svkey", ".svhkey", ".vp", ".key", ".cert", ".der", ".req", ".p8", ".pem", ".so"}

