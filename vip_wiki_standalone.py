#!/usr/bin/env python3
"""Single-file SV/UVM wiki graph generator.

Copy only this file into an offline/internal environment, then run:

  python vip_wiki_standalone.py --src path/to/vip_dir --out atlas_wiki.html

It scans readable .sv/.svh/.v files and writes standalone HTML views plus an
AI-friendly JSON atlas. No pip packages, no network, no local helper scripts.
Default outputs are atlas_wiki.html, atlas_tree.html, atlas_ports.html,
atlas_arch.html, and atlas_ai.json.
Graphviz DOT files are also generated by default for hierarchy and TLM diagrams.
"""

