        used: set[str] = set()
        for lname, roles in layers:
            members = [n for n in selected if str(class_by_name[n].get("role", "class")) in roles][:45]
            used.update(members)
            lines.append(f"  subgraph cluster_{lname} {{ label={dot_q(lname)}; color=\"#e2e8f0\"; style=\"rounded\";")
            lines.extend("  " + class_node(n).strip() for n in members)
            lines.append("  }")
        others = [n for n in selected if n not in used][:35]
        if others:
            lines.append("  subgraph cluster_other { label=\"other\"; color=\"#e2e8f0\"; style=\"rounded\";")
            lines.extend("  " + class_node(n).strip() for n in others)
            lines.append("  }")
        for edge in edges:
            kind = str(edge.get("kind", ""))
            src = str(edge.get("src", "")).split(".")[0]
            dst = str(edge.get("dst", ""))
            if kind not in {"creates", "has_member"} or src not in selected_set or dst not in selected_set:
                continue
            lines.append(f"  {dot_id('class:' + src)} -> {dot_id('class:' + dst)} [label={dot_q(edge.get('instance') or kind)}, color=\"#2563eb\"];")
